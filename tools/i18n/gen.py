"""Build web/js/i18n/vi-data.js from the data files' strings and tools/i18n/vi-data.json (English → Vietnamese).

python3 tools/i18n/gen.py           # writes vi-data.js; lists strings in web/data that still need a translation
Add missing ones to vi-data.json (a proper name may map to itself) and run again.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from extract import candidates  # noqa: E402

here = pathlib.Path(__file__).resolve().parent
tr = json.loads((here / "vi-data.json").read_text(encoding="utf-8"))
c = candidates()
missing = [k for k in c if not tr.get(k)]
d = {k: tr[k] for k in c if tr.get(k)}
body = ",\n".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}" for k, v in d.items())
(here.parents[1] / "web/js/i18n/vi-data.js").write_text(
    "// Generated by tools/i18n/gen.py from web/data/*.json strings and tools/i18n/vi-data.json; edit those, not this file.\n"
    "export default {\n" + body + "\n};\n", encoding="utf-8")
print("entries", len(d), "untranslated", len(missing))
for k in missing:
    print("  MISSING:", json.dumps(k, ensure_ascii=False))
sys.exit(1 if missing else 0)
